import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = ROOT / "database" / "seed_batches" / "grammar-a1-batch-1.json"
DEFAULT_OUTPUT = ROOT / "database" / "seed_batches" / "grammar-a1-batch-1.sql"


def load_batch(path=DEFAULT_INPUT):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def validate_batch(batch):
    courses = batch.get("courses", [])
    if len(courses) not in (1, 2):
        raise ValueError("Batch must contain one or two courses")
    course_keys = set()
    seen_prompts = set()
    seen_signatures = set()
    for course in courses:
        course_key = (
            " ".join(course.get("teacherEmail", "").casefold().split()),
            " ".join(course.get("name", "").casefold().split()),
        )
        if not all(course_key) or not course.get("type") or not course.get("level"):
            raise ValueError("Each course needs teacherEmail, name, type, and level")
        if course_key in course_keys:
            raise ValueError("Duplicate course teacher/name pair")
        course_keys.add(course_key)
        if len(course.get("topics", [])) != 2:
            raise ValueError("Each course must contain two topics")
        if any(len(topic.get("lessons", [])) != 1 for topic in course["topics"]):
            raise ValueError("Each topic must contain exactly one lesson")
        lessons = [lesson for topic in course["topics"] for lesson in topic["lessons"]]
        if len(lessons) != 2:
            raise ValueError("Each course must contain two lessons")
        for lesson in lessons:
            if len(lesson["questions"]) != 5:
                raise ValueError("Each lesson must contain five questions")
            for question in lesson["questions"]:
                prompt = " ".join(question["questionText"].casefold().split())
                signature = (
                    " ".join(question["correctAnswer"].casefold().split()),
                    tuple(
                        sorted(
                            " ".join(option["text"].casefold().split())
                            for option in question["options"]
                        )
                    ),
                )
                if prompt in seen_prompts or signature in seen_signatures:
                    raise ValueError("Duplicate question prompt or option signature")
                seen_prompts.add(prompt)
                seen_signatures.add(signature)
                if len(question["options"]) != 4 or sum(
                    option["isCorrect"] for option in question["options"]
                ) != 1:
                    raise ValueError("Each question needs four options and one correct option")
                correct_options = [
                    option["text"]
                    for option in question["options"]
                    if option["isCorrect"]
                ]
                if correct_options[0] != question["correctAnswer"]:
                    raise ValueError("correctAnswer must match the correct option")
    return batch


def sql_literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def render_sql(batch):
    validate_batch(batch)
    lines = [
        "-- Generated by build_grammar_a1_seed.py; apply to local/dev only.",
        "BEGIN;",
    ]
    for course_index, course in enumerate(batch["courses"], 1):
        teacher = sql_literal(course["teacherEmail"])
        name = sql_literal(course["name"])
        lines += [
            f"-- Course {course_index}: {course['name']}",
            "DO $$ DECLARE v_course_id bigint; v_teacher_id bigint; v_topic_id bigint; v_lesson_id bigint; v_question_id bigint; v_revision_id bigint; v_topic_revision_id bigint; v_lesson_revision_id bigint; v_question_revision_id bigint; v_option_id bigint; BEGIN",
            f"  SELECT u.id INTO v_teacher_id FROM users u WHERE u.email = {teacher} AND u.role = 'TEACHER';",
            "  IF v_teacher_id IS NULL THEN RAISE EXCEPTION 'Missing teacher for batch course'; END IF;",
            f"  SELECT c.id INTO v_course_id FROM courses c WHERE c.teacher_id = v_teacher_id AND c.name = {name};",
            f"  IF v_course_id IS NULL THEN INSERT INTO courses (teacher_id,name,description,type,level,status,pricing_type,price_status) VALUES (v_teacher_id,{name},{sql_literal(course['description'])},{sql_literal(course['type'])},{sql_literal(course['level'])},'DRAFT','FREE','NONE') RETURNING id INTO v_course_id; ELSE UPDATE courses SET description={sql_literal(course['description'])}, type={sql_literal(course['type'])}, level={sql_literal(course['level'])}, updated_at=CURRENT_TIMESTAMP WHERE id=v_course_id; END IF;",
            f"  SELECT id INTO v_revision_id FROM course_revisions WHERE course_id=v_course_id ORDER BY revision_number DESC LIMIT 1;",
            f"  IF v_revision_id IS NULL THEN INSERT INTO course_revisions (course_id,teacher_id,revision_number,status,name,description,type,level,order_index) VALUES (v_course_id,v_teacher_id,1,'DRAFT',{name},{sql_literal(course['description'])},{sql_literal(course['type'])},{sql_literal(course['level'])},0) RETURNING id INTO v_revision_id; END IF;",
            "  IF NOT EXISTS (SELECT 1 FROM topic_revisions WHERE revision_id=v_revision_id) THEN",
        ]
        for topic_index, topic in enumerate(course["topics"], 1):
            lines += [
                f"  SELECT t.id INTO v_topic_id FROM topics t WHERE t.course_id=v_course_id AND t.name={sql_literal(topic['name'])};",
                f"  IF v_topic_id IS NULL THEN INSERT INTO topics (course_id,name,description,order_index) VALUES (v_course_id,{sql_literal(topic['name'])},{sql_literal(topic['description'])},{topic_index}) RETURNING id INTO v_topic_id; ELSE UPDATE topics SET description={sql_literal(topic['description'])}, order_index={topic_index} WHERE id=v_topic_id; END IF;",
                f"  INSERT INTO topic_revisions (revision_id,source_topic_id,name,description,order_index) VALUES (v_revision_id,v_topic_id,{sql_literal(topic['name'])},{sql_literal(topic['description'])},{topic_index}) RETURNING id INTO v_topic_revision_id;",
            ]
            for lesson_index, lesson in enumerate(topic["lessons"], 1):
                lines += [
                    f"  SELECT l.id INTO v_lesson_id FROM lessons l WHERE l.topic_id=v_topic_id AND l.title={sql_literal(lesson['title'])};",
                    f"  IF v_lesson_id IS NULL THEN INSERT INTO lessons (topic_id,teacher_id,title,description,content,skill_type,order_index,status) VALUES (v_topic_id,v_teacher_id,{sql_literal(lesson['title'])},{sql_literal(lesson['description'])},{sql_literal(lesson['content'])},{sql_literal(lesson['skillType'])},{lesson_index},'DRAFT') RETURNING id INTO v_lesson_id; ELSE UPDATE lessons SET description={sql_literal(lesson['description'])}, content={sql_literal(lesson['content'])}, order_index={lesson_index}, updated_at=CURRENT_TIMESTAMP WHERE id=v_lesson_id; END IF;",
                    f"  INSERT INTO lesson_revisions (topic_revision_id,source_lesson_id,teacher_id,title,description,content,skill_type,order_index,xp_reward,is_placement_test) VALUES (v_topic_revision_id,v_lesson_id,v_teacher_id,{sql_literal(lesson['title'])},{sql_literal(lesson['description'])},{sql_literal(lesson['content'])},{sql_literal(lesson['skillType'])},{lesson_index},10,FALSE) RETURNING id INTO v_lesson_revision_id;",
                ]
                for question_index, question in enumerate(lesson["questions"], 1):
                    lines += [
                        f"  SELECT q.id INTO v_question_id FROM questions q WHERE q.lesson_id=v_lesson_id AND q.question_text={sql_literal(question['questionText'])};",
                        f"  IF v_question_id IS NULL THEN INSERT INTO questions (lesson_id,teacher_id,type,question_text,explanation,correct_answer,knowledge_point,order_index,difficulty,xp_reward,status) VALUES (v_lesson_id,v_teacher_id,'MULTIPLE_CHOICE',{sql_literal(question['questionText'])},{sql_literal(question['explanation'])},{sql_literal(question['correctAnswer'])},{sql_literal(question['knowledgePoint'])},{question_index},{sql_literal(question['difficulty'])},10,'DRAFT') RETURNING id INTO v_question_id; ELSE UPDATE questions SET explanation={sql_literal(question['explanation'])}, correct_answer={sql_literal(question['correctAnswer'])}, knowledge_point={sql_literal(question['knowledgePoint'])}, order_index={question_index}, difficulty={sql_literal(question['difficulty'])}, updated_at=CURRENT_TIMESTAMP WHERE id=v_question_id; END IF;",
                        f"  INSERT INTO question_revisions (lesson_revision_id,source_question_id,teacher_id,type,question_text,explanation,correct_answer,knowledge_point,order_index,difficulty,xp_reward) VALUES (v_lesson_revision_id,v_question_id,v_teacher_id,'MULTIPLE_CHOICE',{sql_literal(question['questionText'])},{sql_literal(question['explanation'])},{sql_literal(question['correctAnswer'])},{sql_literal(question['knowledgePoint'])},{question_index},{sql_literal(question['difficulty'])},10) RETURNING id INTO v_question_revision_id;",
                    ]
                    lines.append(
                        "  IF NOT EXISTS (SELECT 1 FROM question_options qo WHERE qo.question_id=v_question_id) THEN"
                    )
                    for option_index, option in enumerate(question["options"], 1):
                        lines.append(
                            f"    INSERT INTO question_options (question_id,option_text,is_correct,order_index,is_active) VALUES (v_question_id,{sql_literal(option['text'])},{str(option['isCorrect']).upper()},{option_index},TRUE) RETURNING id INTO v_option_id;"
                        )
                        lines.append(
                            f"    INSERT INTO question_option_revisions (question_revision_id,source_option_id,option_text,is_correct,order_index) VALUES (v_question_revision_id,v_option_id,{sql_literal(option['text'])},{str(option['isCorrect']).upper()},{option_index});"
                        )
                    lines.append("  END IF;")
                    lines.append(
                        "  IF EXISTS (SELECT 1 FROM question_options qo WHERE qo.question_id=v_question_id) AND NOT EXISTS (SELECT 1 FROM question_option_revisions qor WHERE qor.question_revision_id=v_question_revision_id) THEN"
                    )
                    lines.append(
                        "    INSERT INTO question_option_revisions (question_revision_id,source_option_id,option_text,is_correct,order_index) SELECT v_question_revision_id,qo.id,qo.option_text,qo.is_correct,qo.order_index FROM question_options qo WHERE qo.question_id=v_question_id ORDER BY qo.order_index,qo.id;"
                    )
                    lines.append("  END IF;")
        lines += ["  END IF;", "END $$;"]
    lines.append("COMMIT;")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    sql = render_sql(load_batch(args.input))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(sql, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
