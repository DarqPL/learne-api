def load_batch(path=DEFAULT_INPUT):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def sql_literal(value):
    return "'" + str(value).replace("'", "''") + "'"


def lesson_content(lesson):
    examples = "\n".join(f"- {example}" for example in lesson["examples"])
    errors = "\n".join(f"- {error}" for error in lesson["commonErrors"])
    return (
        f"Objective: {lesson['objective']}\n"
        f"Content: {lesson['content']}\n"
        f"Examples:\n{examples}\n"
        f"Common errors and corrections:\n{errors}\n"
        f"Guided practice: {lesson['guidedPractice']}\n"
        f"Summary: {lesson['summary']}"
    )


def validate_batch(batch):
    course = batch.get("course", {})
    lessons = batch.get("lessons", [])
    if not course.get("teacherEmail") or not course.get("name"):
        raise ValueError("Batch course needs teacherEmail and name")
    if course.get("type") != "GRAMMAR" or course.get("level") != "A2":
        raise ValueError("A2 grammar metadata is required")
    if course.get("status") != "DRAFT" or course.get("pricingType") != "FREE":
        raise ValueError("A2 pilot must remain DRAFT and FREE")
    if len(lessons) != 4 or any(len(lesson.get("questions", [])) != 10 for lesson in lessons):
        raise ValueError("Batch must contain four lessons with ten questions each")
    prompts = set()
    for lesson in lessons:
        for field in ("objective", "content", "examples", "commonErrors", "guidedPractice", "summary"):
            if not lesson.get(field):
                raise ValueError(f"Lesson field is required: {field}")
        for question in lesson["questions"]:
            if question.get("type") != "MULTIPLE_CHOICE":
                raise ValueError("A2 pilot supports MULTIPLE_CHOICE only")
            prompt = " ".join(question.get("questionText", "").casefold().split())
            if not prompt or prompt in prompts:
                raise ValueError("Question prompts must be unique")
            prompts.add(prompt)
            options = question.get("options", [])
            if len(options) != 4 or sum(option.get("isCorrect", False) for option in options) != 1:
                raise ValueError("Each question needs four options and one correct option")
            correct = next(option["text"] for option in options if option["isCorrect"])
            if correct != question.get("correctAnswer"):
                raise ValueError("correctAnswer must match the correct option")
    return batch


