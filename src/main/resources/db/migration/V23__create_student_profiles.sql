CREATE TABLE student_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    phone_number VARCHAR(30),
    date_of_birth DATE,
    bio TEXT,
    learning_goal TEXT,
    current_level VARCHAR(10),
    daily_learning_minutes INTEGER,
    preferred_skills_json TEXT,
    avatar_url VARCHAR(1024),
    avatar_public_id VARCHAR(255),
    public_profile_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    show_email BOOLEAN NOT NULL DEFAULT FALSE,
    show_phone_number BOOLEAN NOT NULL DEFAULT FALSE,
    show_date_of_birth BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT student_profiles_user_id_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT student_profiles_current_level_check CHECK (
        current_level IS NULL OR current_level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')
    ),
    CONSTRAINT student_profiles_daily_learning_minutes_check CHECK (
        daily_learning_minutes IS NULL OR (daily_learning_minutes >= 0 AND daily_learning_minutes <= 1440)
    )
);
