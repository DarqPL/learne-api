ALTER TABLE course_revisions ADD COLUMN cover_image_url VARCHAR(1024);

ALTER TABLE course_revisions ADD COLUMN cover_image_public_id VARCHAR(255);

ALTER TABLE course_revisions
    ADD CONSTRAINT course_revisions_cover_pair_check
        CHECK ((cover_image_url IS NULL) = (cover_image_public_id IS NULL));

CREATE TABLE course_cover_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
    teacher_id BIGINT NOT NULL REFERENCES users(id),
    image_url VARCHAR(1024) NOT NULL,
    image_public_id VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    rejection_reason TEXT,
    submitted_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT course_cover_reviews_status_check
        CHECK (status IN ('PENDING_REVIEW', 'APPROVED', 'REJECTED', 'SUPERSEDED', 'CANCELLED'))
);

CREATE INDEX idx_course_cover_reviews_status_submitted
    ON course_cover_reviews(status, submitted_at, id);

CREATE INDEX idx_course_cover_reviews_course_status
    ON course_cover_reviews(course_id, status);

CREATE TABLE course_pending_review_snapshots (
    course_id BIGINT PRIMARY KEY REFERENCES courses(id) ON DELETE CASCADE,
    snapshot_kind VARCHAR(32) NOT NULL,
    course_revision_id BIGINT UNIQUE REFERENCES course_revisions(id) ON DELETE CASCADE,
    cover_review_id BIGINT UNIQUE REFERENCES course_cover_reviews(id) ON DELETE CASCADE,
    version BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT course_pending_review_snapshots_target_check CHECK (
        (snapshot_kind = 'COURSE_REVISION' AND course_revision_id IS NOT NULL AND cover_review_id IS NULL)
        OR
        (snapshot_kind = 'COVER_ONLY' AND course_revision_id IS NULL AND cover_review_id IS NOT NULL)
    )
);

UPDATE course_revisions older
SET status = 'SUPERSEDED'
WHERE older.status = 'PENDING_REVIEW'
  AND EXISTS (
      SELECT 1
      FROM course_revisions newer
      WHERE newer.course_id = older.course_id
        AND newer.status = 'PENDING_REVIEW'
        AND newer.revision_number > older.revision_number
  );

INSERT INTO course_pending_review_snapshots (course_id, snapshot_kind, course_revision_id)
SELECT revision.course_id, 'COURSE_REVISION', revision.id
FROM course_revisions revision
WHERE revision.status = 'PENDING_REVIEW';
