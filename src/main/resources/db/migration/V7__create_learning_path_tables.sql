CREATE TABLE learning_paths (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    weaknesses_json TEXT,
    source VARCHAR(50) NOT NULL DEFAULT 'AI_SERVICE',
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_learning_paths_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_learning_paths_status CHECK (status IN ('ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_learning_paths_source CHECK (source IN ('AI_SERVICE', 'FALLBACK_RULE'))
);

CREATE TABLE learning_path_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path_id BIGINT NOT NULL,
    lesson_id BIGINT NOT NULL,
    sequence_order INT NOT NULL,
    reason TEXT,
    score NUMERIC(5,4) NOT NULL DEFAULT 0,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_learning_path_items_path FOREIGN KEY (path_id) REFERENCES learning_paths(id) ON DELETE CASCADE,
    CONSTRAINT fk_learning_path_items_lesson FOREIGN KEY (lesson_id) REFERENCES lessons(id),
    CONSTRAINT uq_learning_path_items_path_lesson UNIQUE (path_id, lesson_id),
    CONSTRAINT uq_learning_path_items_path_order UNIQUE (path_id, sequence_order),
    CONSTRAINT ck_learning_path_items_sequence_order CHECK (sequence_order > 0),
    CONSTRAINT ck_learning_path_items_score CHECK (score >= 0 AND score <= 1)
);

CREATE INDEX idx_learning_paths_user_status ON learning_paths(user_id, status);
CREATE INDEX idx_learning_paths_generated_at ON learning_paths(generated_at);
CREATE INDEX idx_learning_path_items_path_completed_order ON learning_path_items(path_id, completed, sequence_order);
CREATE INDEX idx_learning_path_items_lesson ON learning_path_items(lesson_id);
