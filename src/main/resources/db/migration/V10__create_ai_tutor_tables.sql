CREATE TABLE ai_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(120) NOT NULL,
    practice_type VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL,
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cleanup_warn_at TIMESTAMP NOT NULL,
    archive_after TIMESTAMP NOT NULL,
    archived_at TIMESTAMP,
    delete_after TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_conversations_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_ai_conversations_practice_type CHECK (practice_type IN ('FREE_CHAT', 'ROLEPLAY', 'WRITING_PRACTICE')),
    CONSTRAINT ck_ai_conversations_status CHECK (status IN ('ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_ai_conversations_title_length CHECK (CHAR_LENGTH(title) BETWEEN 1 AND 120),
    CONSTRAINT ck_ai_conversations_archive_metadata CHECK (
        (status = 'ACTIVE') OR (status = 'ARCHIVED' AND archived_at IS NOT NULL AND delete_after IS NOT NULL)
    )
);

CREATE TABLE ai_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    sender_type VARCHAR(20) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_messages_conversation FOREIGN KEY (conversation_id) REFERENCES ai_conversations(id) ON DELETE CASCADE,
    CONSTRAINT ck_ai_messages_sender_type CHECK (sender_type IN ('USER', 'AI')),
    CONSTRAINT ck_ai_messages_message_length CHECK (CHAR_LENGTH(message) BETWEEN 1 AND 4000)
);

CREATE TABLE ai_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL,
    error_type VARCHAR(50) NOT NULL,
    original_text VARCHAR(1000) NOT NULL,
    corrected_text VARCHAR(1000) NOT NULL,
    explanation VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_feedback_message FOREIGN KEY (message_id) REFERENCES ai_messages(id) ON DELETE CASCADE,
    CONSTRAINT uq_ai_feedback_message UNIQUE (message_id),
    CONSTRAINT ck_ai_feedback_type CHECK (error_type IN ('GRAMMAR', 'VOCABULARY', 'WORD_CHOICE', 'STYLE', 'OTHER')),
    CONSTRAINT ck_ai_feedback_original_text_length CHECK (CHAR_LENGTH(original_text) BETWEEN 1 AND 1000),
    CONSTRAINT ck_ai_feedback_corrected_text_length CHECK (CHAR_LENGTH(corrected_text) BETWEEN 1 AND 1000),
    CONSTRAINT ck_ai_feedback_explanation_length CHECK (CHAR_LENGTH(explanation) BETWEEN 1 AND 1000)
);

CREATE INDEX idx_ai_conversations_user_status_last_message ON ai_conversations(user_id, status, last_message_at DESC);
CREATE INDEX idx_ai_conversations_status_archive_after ON ai_conversations(status, archive_after);
CREATE INDEX idx_ai_conversations_status_delete_after ON ai_conversations(status, delete_after);
CREATE INDEX idx_ai_messages_conversation_created_at ON ai_messages(conversation_id, created_at ASC);
