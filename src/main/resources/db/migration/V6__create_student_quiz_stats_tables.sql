CREATE TABLE quiz_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    course_enrollment_id BIGINT NOT NULL,
    lesson_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    score_percent INT NOT NULL DEFAULT 0,
    earned_xp INT NOT NULL DEFAULT 0,
    passed BOOLEAN NOT NULL DEFAULT FALSE,
    submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_quiz_attempts_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_quiz_attempts_enrollment FOREIGN KEY (course_enrollment_id) REFERENCES course_enrollments(id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_attempts_lesson FOREIGN KEY (lesson_id) REFERENCES lessons(id),
    CONSTRAINT ck_quiz_attempts_status CHECK (status IN ('SUBMITTED')),
    CONSTRAINT ck_quiz_attempts_score_percent CHECK (score_percent >= 0 AND score_percent <= 100),
    CONSTRAINT ck_quiz_attempts_earned_xp CHECK (earned_xp >= 0)
);

CREATE TABLE question_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_attempt_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    answer_text TEXT,
    selected_option_id BIGINT,
    selected_option_ids_json TEXT,
    correct BOOLEAN NOT NULL DEFAULT FALSE,
    score_percent INT NOT NULL DEFAULT 0,
    earned_xp INT NOT NULL DEFAULT 0,
    grading_method VARCHAR(50) NOT NULL,
    feedback TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_question_answers_attempt FOREIGN KEY (quiz_attempt_id) REFERENCES quiz_attempts(id) ON DELETE CASCADE,
    CONSTRAINT fk_question_answers_question FOREIGN KEY (question_id) REFERENCES questions(id),
    CONSTRAINT fk_question_answers_selected_option FOREIGN KEY (selected_option_id) REFERENCES question_options(id),
    CONSTRAINT uq_question_answers_attempt_question UNIQUE (quiz_attempt_id, question_id),
    CONSTRAINT ck_question_answers_score_percent CHECK (score_percent >= 0 AND score_percent <= 100),
    CONSTRAINT ck_question_answers_earned_xp CHECK (earned_xp >= 0),
    CONSTRAINT ck_question_answers_grading_method CHECK (grading_method IN ('OPTION_MATCH', 'EXACT_MATCH', 'MANUAL_TARGET_ONLY'))
);

CREATE TABLE user_stats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    total_xp INT NOT NULL DEFAULT 0,
    current_streak_days INT NOT NULL DEFAULT 0,
    longest_streak_days INT NOT NULL DEFAULT 0,
    last_activity_date DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_stats_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uq_user_stats_user UNIQUE (user_id),
    CONSTRAINT ck_user_stats_total_xp CHECK (total_xp >= 0),
    CONSTRAINT ck_user_stats_current_streak_days CHECK (current_streak_days >= 0),
    CONSTRAINT ck_user_stats_longest_streak_days CHECK (longest_streak_days >= 0)
);

CREATE TABLE learning_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    source_type VARCHAR(50) NOT NULL,
    source_id BIGINT NOT NULL,
    activity_date DATE NOT NULL,
    xp_earned INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_learning_activities_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_learning_activities_source_type CHECK (source_type IN ('LESSON_QUIZ_PASS')),
    CONSTRAINT ck_learning_activities_xp_earned CHECK (xp_earned >= 0),
    CONSTRAINT uq_learning_activities_user_source_date UNIQUE (user_id, source_type, source_id, activity_date)
);

CREATE INDEX idx_quiz_attempts_user_lesson ON quiz_attempts(user_id, lesson_id);
CREATE INDEX idx_quiz_attempts_enrollment_lesson ON quiz_attempts(course_enrollment_id, lesson_id);
CREATE INDEX idx_quiz_attempts_submitted_at ON quiz_attempts(submitted_at);
CREATE INDEX idx_question_answers_question ON question_answers(question_id);
CREATE INDEX idx_learning_activities_user_activity_date ON learning_activities(user_id, activity_date);
