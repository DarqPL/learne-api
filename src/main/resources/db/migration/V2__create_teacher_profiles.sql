CREATE TABLE teacher_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE,
    bio TEXT NOT NULL DEFAULT '',
    expertise VARCHAR(255) NOT NULL DEFAULT '',
    years_of_experience INTEGER NOT NULL DEFAULT 0,
    avatar_url VARCHAR(1024),
    introduction_video_url VARCHAR(1024),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT teacher_profiles_user_id_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT teacher_profiles_status_check CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),
    CONSTRAINT teacher_profiles_years_of_experience_check CHECK (years_of_experience >= 0)
);

CREATE INDEX idx_teacher_profiles_status ON teacher_profiles(status);
