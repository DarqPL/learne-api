CREATE TABLE course_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    revision_number INT NOT NULL,
    status VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    type VARCHAR(50) NOT NULL,
    level VARCHAR(50) NOT NULL,
    order_index INT NOT NULL DEFAULT 0,
    rejection_reason TEXT,
    submitted_at TIMESTAMP,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP,
    published_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_course_revisions_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
    CONSTRAINT fk_course_revisions_teacher FOREIGN KEY (teacher_id) REFERENCES users(id),
    CONSTRAINT fk_course_revisions_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id),
    CONSTRAINT uq_course_revisions_number UNIQUE (course_id, revision_number)
);

CREATE TABLE topic_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id BIGINT NOT NULL,
    source_topic_id BIGINT,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    order_index INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_topic_revisions_revision FOREIGN KEY (revision_id) REFERENCES course_revisions(id) ON DELETE CASCADE,
    CONSTRAINT fk_topic_revisions_source_topic FOREIGN KEY (source_topic_id) REFERENCES topics(id) ON DELETE SET NULL
);

CREATE TABLE lesson_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_revision_id BIGINT NOT NULL,
    source_lesson_id BIGINT,
    teacher_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    content TEXT,
    skill_type VARCHAR(50) NOT NULL,
    audio_url VARCHAR(1024),
    audio_public_id VARCHAR(255),
    order_index INT NOT NULL DEFAULT 0,
    xp_reward INT NOT NULL DEFAULT 0,
    is_placement_test BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_lesson_revisions_topic FOREIGN KEY (topic_revision_id) REFERENCES topic_revisions(id) ON DELETE CASCADE,
    CONSTRAINT fk_lesson_revisions_source_lesson FOREIGN KEY (source_lesson_id) REFERENCES lessons(id) ON DELETE SET NULL,
    CONSTRAINT fk_lesson_revisions_teacher FOREIGN KEY (teacher_id) REFERENCES users(id)
);

CREATE TABLE question_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_revision_id BIGINT NOT NULL,
    source_question_id BIGINT,
    teacher_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    question_text TEXT NOT NULL,
    explanation TEXT,
    correct_answer VARCHAR(1024),
    knowledge_point VARCHAR(255),
    order_index INT NOT NULL DEFAULT 0,
    difficulty VARCHAR(50),
    xp_reward INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_question_revisions_lesson FOREIGN KEY (lesson_revision_id) REFERENCES lesson_revisions(id) ON DELETE CASCADE,
    CONSTRAINT fk_question_revisions_source_question FOREIGN KEY (source_question_id) REFERENCES questions(id) ON DELETE SET NULL,
    CONSTRAINT fk_question_revisions_teacher FOREIGN KEY (teacher_id) REFERENCES users(id)
);

CREATE TABLE question_option_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_revision_id BIGINT NOT NULL,
    source_option_id BIGINT,
    option_text VARCHAR(1024) NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    order_index INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_option_revisions_question FOREIGN KEY (question_revision_id) REFERENCES question_revisions(id) ON DELETE CASCADE,
    CONSTRAINT fk_option_revisions_source_option FOREIGN KEY (source_option_id) REFERENCES question_options(id) ON DELETE SET NULL
);

CREATE INDEX idx_course_revisions_course_status ON course_revisions(course_id, status);
CREATE INDEX idx_course_revisions_teacher_status ON course_revisions(teacher_id, status);
CREATE INDEX idx_course_revisions_latest ON course_revisions(course_id, revision_number DESC);
CREATE INDEX idx_topic_revisions_revision ON topic_revisions(revision_id);
CREATE INDEX idx_lesson_revisions_topic ON lesson_revisions(topic_revision_id);
CREATE INDEX idx_lesson_revisions_teacher ON lesson_revisions(teacher_id);
CREATE INDEX idx_question_revisions_lesson ON question_revisions(lesson_revision_id);
CREATE INDEX idx_question_revisions_teacher ON question_revisions(teacher_id);
CREATE INDEX idx_option_revisions_question ON question_option_revisions(question_revision_id);

