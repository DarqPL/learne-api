INSERT INTO topic_revisions (
    revision_id,
    source_topic_id,
    name,
    description,
    order_index
)
SELECT
    cr.id,
    t.id,
    t.name,
    t.description,
    t.order_index
FROM topics t
JOIN course_revisions cr ON cr.course_id = t.course_id AND cr.revision_number = 1;

INSERT INTO lesson_revisions (
    topic_revision_id,
    source_lesson_id,
    teacher_id,
    title,
    description,
    content,
    skill_type,
    audio_url,
    audio_public_id,
    order_index,
    xp_reward,
    is_placement_test
)
SELECT
    tr.id,
    l.id,
    l.teacher_id,
    l.title,
    l.description,
    l.content,
    l.skill_type,
    l.audio_url,
    l.audio_public_id,
    l.order_index,
    l.xp_reward,
    l.is_placement_test
FROM lessons l
JOIN topic_revisions tr ON tr.source_topic_id = l.topic_id;

INSERT INTO question_revisions (
    lesson_revision_id,
    source_question_id,
    teacher_id,
    type,
    question_text,
    explanation,
    correct_answer,
    knowledge_point,
    order_index,
    difficulty,
    xp_reward
)
SELECT
    lr.id,
    q.id,
    q.teacher_id,
    q.type,
    q.question_text,
    q.explanation,
    q.correct_answer,
    q.knowledge_point,
    q.order_index,
    q.difficulty,
    q.xp_reward
FROM questions q
JOIN lesson_revisions lr ON lr.source_lesson_id = q.lesson_id;

INSERT INTO question_option_revisions (
    question_revision_id,
    source_option_id,
    option_text,
    is_correct,
    order_index
)
SELECT
    qr.id,
    qo.id,
    qo.option_text,
    qo.is_correct,
    qo.order_index
FROM question_options qo
JOIN question_revisions qr ON qr.source_question_id = qo.question_id;
