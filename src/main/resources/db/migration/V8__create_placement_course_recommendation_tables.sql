CREATE TABLE placement_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    score_percent INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_placement_attempts_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_placement_attempts_status CHECK (status IN ('IN_PROGRESS', 'SUBMITTED', 'EXPIRED')),
    CONSTRAINT ck_placement_attempts_score_percent CHECK (score_percent >= 0 AND score_percent <= 100)
);

CREATE TABLE placement_attempt_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placement_attempt_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    sequence_order INT NOT NULL,
    skill VARCHAR(50) NOT NULL,
    CONSTRAINT fk_placement_attempt_questions_attempt FOREIGN KEY (placement_attempt_id) REFERENCES placement_attempts(id) ON DELETE CASCADE,
    CONSTRAINT fk_placement_attempt_questions_question FOREIGN KEY (question_id) REFERENCES questions(id),
    CONSTRAINT uq_placement_attempt_questions_attempt_question UNIQUE (placement_attempt_id, question_id),
    CONSTRAINT uq_placement_attempt_questions_attempt_order UNIQUE (placement_attempt_id, sequence_order),
    CONSTRAINT ck_placement_attempt_questions_sequence CHECK (sequence_order > 0),
    CONSTRAINT ck_placement_attempt_questions_skill CHECK (skill IN ('VOCABULARY', 'GRAMMAR', 'READING', 'WRITING'))
);

CREATE TABLE placement_attempt_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placement_attempt_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    answer_text TEXT,
    selected_option_id BIGINT,
    selected_option_ids_json TEXT,
    correct BOOLEAN NOT NULL DEFAULT FALSE,
    score_percent INT NOT NULL DEFAULT 0,
    feedback TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_placement_attempt_answers_attempt FOREIGN KEY (placement_attempt_id) REFERENCES placement_attempts(id) ON DELETE CASCADE,
    CONSTRAINT fk_placement_attempt_answers_question FOREIGN KEY (question_id) REFERENCES questions(id),
    CONSTRAINT fk_placement_attempt_answers_selected_option FOREIGN KEY (selected_option_id) REFERENCES question_options(id),
    CONSTRAINT uq_placement_attempt_answers_attempt_question UNIQUE (placement_attempt_id, question_id),
    CONSTRAINT ck_placement_attempt_answers_score_percent CHECK (score_percent >= 0 AND score_percent <= 100)
);

CREATE TABLE placement_preferences (
    user_id BIGINT PRIMARY KEY,
    skipped_at TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_placement_preferences_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE course_recommendation_paths (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    active_user_id BIGINT,
    weaknesses_json TEXT,
    source VARCHAR(50) NOT NULL DEFAULT 'AI_SERVICE',
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_course_recommendation_paths_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT uq_course_recommendation_paths_active_user UNIQUE (active_user_id),
    CONSTRAINT ck_course_recommendation_paths_status CHECK (status IN ('ACTIVE', 'ARCHIVED')),
    CONSTRAINT ck_course_recommendation_paths_active_user CHECK (
        (status = 'ACTIVE' AND active_user_id = user_id)
        OR (status <> 'ACTIVE' AND active_user_id IS NULL)
    ),
    CONSTRAINT ck_course_recommendation_paths_source CHECK (source IN ('AI_SERVICE', 'FALLBACK_RULE'))
);

CREATE TABLE course_recommendation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path_id BIGINT NOT NULL,
    course_id BIGINT NOT NULL,
    sequence_order INT NOT NULL,
    reason TEXT,
    score NUMERIC(5,4) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_course_recommendation_items_path FOREIGN KEY (path_id) REFERENCES course_recommendation_paths(id) ON DELETE CASCADE,
    CONSTRAINT fk_course_recommendation_items_course FOREIGN KEY (course_id) REFERENCES courses(id),
    CONSTRAINT uq_course_recommendation_items_path_course UNIQUE (path_id, course_id),
    CONSTRAINT uq_course_recommendation_items_path_order UNIQUE (path_id, sequence_order),
    CONSTRAINT ck_course_recommendation_items_sequence CHECK (sequence_order > 0),
    CONSTRAINT ck_course_recommendation_items_score CHECK (score >= 0 AND score <= 1)
);

CREATE INDEX idx_placement_attempts_user_status ON placement_attempts(user_id, status);
CREATE INDEX idx_placement_attempts_expires_at ON placement_attempts(expires_at);
CREATE INDEX idx_placement_attempt_questions_attempt ON placement_attempt_questions(placement_attempt_id);
CREATE INDEX idx_placement_attempt_questions_question ON placement_attempt_questions(question_id);
CREATE INDEX idx_placement_attempt_answers_attempt ON placement_attempt_answers(placement_attempt_id);
CREATE INDEX idx_placement_attempt_answers_question ON placement_attempt_answers(question_id);
CREATE INDEX idx_placement_attempt_answers_selected_option ON placement_attempt_answers(selected_option_id);
CREATE INDEX idx_course_recommendation_paths_user_status ON course_recommendation_paths(user_id, status);
CREATE INDEX idx_course_recommendation_items_path_order ON course_recommendation_items(path_id, sequence_order);
CREATE INDEX idx_course_recommendation_items_course ON course_recommendation_items(course_id);
