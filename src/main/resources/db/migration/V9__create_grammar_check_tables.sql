CREATE TABLE grammar_checks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    source VARCHAR(50) NOT NULL DEFAULT 'AI_SERVICE',
    input_text TEXT NOT NULL,
    failure_message TEXT,
    course_id BIGINT,
    lesson_id BIGINT,
    question_id BIGINT,
    enrollment_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_grammar_checks_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_grammar_checks_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE SET NULL,
    CONSTRAINT fk_grammar_checks_lesson FOREIGN KEY (lesson_id) REFERENCES lessons(id) ON DELETE SET NULL,
    CONSTRAINT fk_grammar_checks_question FOREIGN KEY (question_id) REFERENCES questions(id) ON DELETE SET NULL,
    CONSTRAINT fk_grammar_checks_enrollment FOREIGN KEY (enrollment_id) REFERENCES course_enrollments(id) ON DELETE SET NULL,
    CONSTRAINT ck_grammar_checks_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_grammar_checks_source CHECK (source IN ('AI_SERVICE')),
    CONSTRAINT ck_grammar_checks_input_length CHECK (CHAR_LENGTH(input_text) BETWEEN 1 AND 2000)
);

CREATE TABLE grammar_check_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id BIGINT NOT NULL,
    sequence_order INT NOT NULL,
    error_text VARCHAR(500) NOT NULL,
    error_type VARCHAR(50) NOT NULL,
    suggestion VARCHAR(500) NOT NULL,
    explanation TEXT NOT NULL,
    start_pos INT NOT NULL,
    end_pos INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_grammar_check_errors_check FOREIGN KEY (check_id) REFERENCES grammar_checks(id) ON DELETE CASCADE,
    CONSTRAINT uq_grammar_check_errors_check_order UNIQUE (check_id, sequence_order),
    CONSTRAINT ck_grammar_check_errors_sequence CHECK (sequence_order > 0),
    CONSTRAINT ck_grammar_check_errors_type CHECK (error_type IN ('GRAMMAR', 'SPELLING', 'PUNCTUATION', 'WORD_CHOICE', 'STYLE', 'OTHER')),
    CONSTRAINT ck_grammar_check_errors_start CHECK (start_pos >= 0),
    CONSTRAINT ck_grammar_check_errors_range CHECK (end_pos > start_pos)
);

CREATE INDEX idx_grammar_checks_user_created_at ON grammar_checks(user_id, created_at DESC);
CREATE INDEX idx_grammar_checks_course ON grammar_checks(course_id);
CREATE INDEX idx_grammar_checks_lesson ON grammar_checks(lesson_id);
CREATE INDEX idx_grammar_checks_question ON grammar_checks(question_id);
CREATE INDEX idx_grammar_checks_enrollment ON grammar_checks(enrollment_id);
