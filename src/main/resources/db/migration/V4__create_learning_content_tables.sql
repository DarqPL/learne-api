CREATE TABLE courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    type VARCHAR(50) NOT NULL,
    level VARCHAR(50) NOT NULL,
    order_index INT NOT NULL DEFAULT 0,
    status VARCHAR(50) NOT NULL,
    rejection_reason TEXT,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP,
    published_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_courses_teacher FOREIGN KEY (teacher_id) REFERENCES users(id),
    CONSTRAINT fk_courses_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id)
);

CREATE TABLE topics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    order_index INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_topics_course FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE
);

CREATE TABLE lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    content TEXT,
    skill_type VARCHAR(50) NOT NULL,
    audio_url VARCHAR(1024),
    audio_public_id VARCHAR(255),
    video_url VARCHAR(1024),
    video_public_id VARCHAR(255),
    order_index INT NOT NULL DEFAULT 0,
    xp_reward INT NOT NULL DEFAULT 0,
    is_locked BOOLEAN NOT NULL DEFAULT FALSE,
    is_placement_test BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(50) NOT NULL,
    rejection_reason TEXT,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP,
    published_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lessons_topic FOREIGN KEY (topic_id) REFERENCES topics(id) ON DELETE CASCADE,
    CONSTRAINT fk_lessons_teacher FOREIGN KEY (teacher_id) REFERENCES users(id),
    CONSTRAINT fk_lessons_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id)
);

CREATE TABLE questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    question_text TEXT NOT NULL,
    explanation TEXT,
    correct_answer VARCHAR(1024),
    knowledge_point VARCHAR(255),
    order_index INT NOT NULL DEFAULT 0,
    difficulty VARCHAR(50),
    xp_reward INT NOT NULL DEFAULT 0,
    status VARCHAR(50) NOT NULL,
    rejection_reason TEXT,
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_questions_lesson FOREIGN KEY (lesson_id) REFERENCES lessons(id) ON DELETE CASCADE,
    CONSTRAINT fk_questions_teacher FOREIGN KEY (teacher_id) REFERENCES users(id),
    CONSTRAINT fk_questions_reviewer FOREIGN KEY (reviewed_by) REFERENCES users(id)
);

CREATE TABLE question_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT NOT NULL,
    option_text VARCHAR(1024) NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    order_index INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_question_options_question FOREIGN KEY (question_id) REFERENCES questions(id) ON DELETE CASCADE
);

CREATE INDEX idx_courses_teacher ON courses(teacher_id);
CREATE INDEX idx_courses_status ON courses(status);
CREATE INDEX idx_courses_type ON courses(type);
CREATE INDEX idx_topics_course ON topics(course_id);
CREATE INDEX idx_lessons_topic ON lessons(topic_id);
CREATE INDEX idx_lessons_skill_type ON lessons(skill_type);
CREATE INDEX idx_questions_lesson ON questions(lesson_id);
CREATE INDEX idx_questions_knowledge_point ON questions(knowledge_point);
CREATE INDEX idx_question_options_question ON question_options(question_id);
