CREATE SEQUENCE answer_event_order_seq AS BIGINT START WITH 1;

ALTER TABLE question_answers
    ADD COLUMN answer_event_order BIGINT;

WITH ordered_answers AS (
    SELECT answer.id,
           row_number() OVER (ORDER BY attempt.submitted_at ASC, answer.id ASC) AS event_order
    FROM question_answers answer
    JOIN quiz_attempts attempt ON attempt.id = answer.quiz_attempt_id
)
UPDATE question_answers answer
SET answer_event_order = ordered_answers.event_order
FROM ordered_answers
WHERE answer.id = ordered_answers.id;

SELECT setval(
    'answer_event_order_seq',
    COALESCE((SELECT MAX(answer_event_order) FROM question_answers), 1),
    (SELECT COUNT(*) > 0 FROM question_answers)
);

ALTER TABLE question_answers
    ALTER COLUMN answer_event_order SET DEFAULT nextval('answer_event_order_seq'),
    ALTER COLUMN answer_event_order SET NOT NULL;

CREATE INDEX idx_quiz_attempts_user_id_id
    ON quiz_attempts(user_id, id);
CREATE INDEX idx_question_answers_attempt_question_event
    ON question_answers(quiz_attempt_id, question_id, answer_event_order);

CREATE TABLE mistake_review_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('IN_PROGRESS', 'SUBMITTED')),
    question_count INTEGER NOT NULL CHECK (question_count BETWEEN 1 AND 10),
    score_percent INTEGER CHECK (score_percent BETWEEN 0 AND 100),
    request_hash VARCHAR(64),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    submitted_at TIMESTAMP
);

CREATE INDEX idx_mistake_review_sessions_user_created
    ON mistake_review_sessions(user_id, created_at DESC, id DESC);

CREATE TABLE mistake_review_session_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES mistake_review_sessions(id) ON DELETE CASCADE,
    question_id BIGINT REFERENCES questions(id) ON DELETE SET NULL,
    source_question_id_snapshot BIGINT NOT NULL,
    question_order INTEGER NOT NULL CHECK (question_order BETWEEN 0 AND 9),
    question_text TEXT NOT NULL,
    question_type VARCHAR(40) NOT NULL,
    options_snapshot TEXT NOT NULL,
    correct_answer_snapshot TEXT,
    explanation_snapshot TEXT,
    UNIQUE (session_id, question_order),
    UNIQUE (session_id, id)
);

CREATE INDEX idx_mistake_review_session_questions_session
    ON mistake_review_session_questions(session_id, question_order);

CREATE TABLE mistake_review_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_question_id BIGINT NOT NULL REFERENCES mistake_review_session_questions(id) ON DELETE CASCADE,
    answer_text TEXT,
    selected_option_id BIGINT,
    correct BOOLEAN NOT NULL,
    score_percent INTEGER NOT NULL CHECK (score_percent BETWEEN 0 AND 100),
    grading_method VARCHAR(50) NOT NULL,
    feedback TEXT,
    correct_answer_display TEXT,
    explanation_snapshot TEXT,
    answer_event_order BIGINT NOT NULL DEFAULT nextval('answer_event_order_seq'),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (session_question_id),
    CHECK ((answer_text IS NULL) <> (selected_option_id IS NULL))
);

CREATE INDEX idx_mistake_review_answers_question_event
    ON mistake_review_answers(session_question_id, answer_event_order);
